#!/usr/bin/env python
"""Adversarial checks on the infinite maze. CPU only, no model, no GPU.

Every property the streaming world rests on is checked here, because each one fails
silently downstream: a maze that disagrees with itself across a chunk border shows up
as a wall the player walks through, and a torch that moves when you look away shows
up as a tile that will not stop re-reconstructing.

    python selftest_maze.py [--seed 1000] [--span 24]
"""
import argparse
import os
import sys

import numpy as np

from infinite_maze import (InfiniteMaze, Chunk, gates_v, gates_h, CELL_M,
                           DIRS, DC, DR, OPP, CHUNK, _fdiv)

FAILS = []


def check(name, ok, detail=""):
    print(f"  {'PASS' if ok else 'FAIL'}  {name}{('  ' + detail) if detail else ''}")
    if not ok:
        FAILS.append(name)
    return ok


def t_determinism(seed, k):
    """Same chunk asked for twice, and after the cache has thrown it away."""
    a = InfiniteMaze(seed, k, cache=8)
    first = {}
    for ch in range(-2, 3):
        for rh in range(-2, 3):
            first[(ch, rh)] = list(a.chunk(ch, rh).walls)
    # walk far enough to evict everything, then come back
    for ch in range(20, 40):
        a.chunk(ch, 17)
    same = all(list(a.chunk(ch, rh).walls) == w for (ch, rh), w in first.items())
    check("chunk is identical after cache eviction", same)

    b = InfiniteMaze(seed, k, cache=4096)
    order_free = all(list(b.chunk(ch, rh).walls) == w
                     for (ch, rh), w in sorted(first.items(), reverse=True))
    check("chunk does not depend on visit order", order_free)

    c = InfiniteMaze(seed + 1, k)
    differs = any(list(c.chunk(ch, rh).walls) != w for (ch, rh), w in first.items())
    check("a different seed gives a different world", differs)

    # Determinism must not be bought with periodicity. If the chunk RNG ignored its
    # coordinates every chunk would still be reproducible, and every seed would still
    # give a different world -- but the labyrinth would be one room of wallpaper
    # repeating forever, which is the opposite of endless. Compare interiors only, so
    # the per-edge gate hashes cannot mask a repeat.
    def interior(ck):
        return tuple(ck.walls[ck._i(x, y)]
                     for y in range(1, k - 1) for x in range(1, k - 1))

    sigs = [interior(a.chunk(ch, rh)) for ch in range(10) for rh in range(10)]
    check("chunks are not copies of each other", len(set(sigs)) == len(sigs),
          f"{len(set(sigs))} distinct interiors of {len(sigs)} chunks")

    shifted = [interior(a.chunk(ch + 137, rh - 89)) for ch in range(10) for rh in range(10)]
    check("the world is not periodic in the chunk lattice",
          len(set(sigs) & set(shifted)) == 0,
          f"{len(set(sigs) & set(shifted))} interiors recur after a shift")


def t_wall_symmetry(seed, k, span):
    """The wall between two cells must be agreed on by both -- above all when the two
    live in different chunks and were generated by different Chunk objects."""
    m = InfiniteMaze(seed, k)
    bad, bad_border, n_border = 0, 0, 0
    for r in range(-span, span):
        for c in range(-span, span):
            for d in DIRS:
                nc, nr = c + DC[d], r + DR[d]
                cross = (_fdiv(c, k), _fdiv(r, k)) != (_fdiv(nc, k), _fdiv(nr, k))
                if cross:
                    n_border += 1
                if m.has_wall(c, r, d) != m.has_wall(nc, nr, OPP[d]):
                    bad += 1
                    bad_border += int(cross)
    check("wall symmetry over every cell pair", bad == 0,
          f"{bad} disagreements ({bad_border} on chunk borders) of "
          f"{(2 * span) ** 2 * 4} pairs, {n_border} crossing")


def t_gate_agreement(seed, k):
    """Neighbouring chunks derive the shared gate set without communicating."""
    m = InfiniteMaze(seed, k)
    bad = 0
    for ch in range(-3, 3):
        for rh in range(-3, 3):
            left, right = m.chunk(ch, rh), m.chunk(ch + 1, rh)
            want = set(gates_v(seed, ch, rh, k))
            got_l = {row for row in range(k) if not left._wall(k - 1, row, 1)}
            got_r = {row for row in range(k) if not right._wall(0, row, 3)}
            if not (want <= got_l and want <= got_r):
                bad += 1
            up, down = m.chunk(ch, rh), m.chunk(ch, rh + 1)
            wanth = set(gates_h(seed, ch, rh, k))
            got_u = {col for col in range(k) if not up._wall(col, k - 1, 2)}
            got_d = {col for col in range(k) if not down._wall(col, 0, 0)}
            if not (wanth <= got_u and wanth <= got_d):
                bad += 1
    check("hashed gates are open from both sides", bad == 0, f"{bad} mismatched edges")

    empty = sum(1 for ch in range(-6, 6) for rh in range(-6, 6)
                if not gates_v(seed, ch, rh, k) or not gates_h(seed, ch, rh, k))
    check("every chunk edge has at least one gate", empty == 0, f"{empty} sealed edges")


def t_chunk_internally_connected(seed, k):
    """Chunk-internal connectivity, which the plane-wide argument depends on."""
    bad = []
    n = 0
    for ch in range(-20, 20):
        for rh in range(-20, 20):
            n += 1
            ck = Chunk(seed, ch, rh, k)
            if len(ck._flood((0, 0))) != k * k:
                bad.append((ch, rh))
    check("each chunk is one connected component before gates", not bad,
          f"{len(bad)} broken of {n} chunks scanned")

    # Scanning random chunks only proves the generator rarely disconnects one -- it
    # cannot prove _repair works, because a chunk that was never broken never exercises
    # it. So break one on purpose: seal a cell off from all four sides and require the
    # repair pass to bring it back into the component.
    ck = Chunk(seed, 0, 0, k)
    victim = (k // 2, k // 2)
    for d in DIRS:
        nc, nr = victim[0] + DC[d], victim[1] + DR[d]
        ck.walls[ck._i(*victim)] |= (1 << d)
        if ck._in(nc, nr):
            ck.walls[ck._i(nc, nr)] |= (1 << OPP[d])
    broke = len(ck._flood((0, 0))) != k * k
    ck._repair()
    check("_repair reconnects a chunk that was sealed on purpose",
          broke and len(ck._flood((0, 0))) == k * k,
          f"sealed={broke}, reconnected={len(ck._flood((0, 0))) == k * k}")


def t_plane_connectivity(seed, k, span):
    """The property the whole design rests on: any cell reaches any other cell.

    Checked by real BFS through the live generator, over both signs of both axes, so
    a wrong floor-division on negative coordinates cannot hide."""
    m = InfiniteMaze(seed, k)
    targets = [(0, 0), (span, span), (-span, span), (span, -span), (-span, -span),
               (3 * span, 0), (0, -3 * span)]
    ok, dists = True, []
    for goal in targets[1:]:
        path = m.bfs(targets[0], goal)
        if path is None:
            ok = False
            print(f"        no path (0,0) -> {goal}")
        else:
            dists.append(len(path))
    check("every probed cell is reachable from the origin", ok,
          f"path lengths {dists}")


def t_torches(seed, k, span):
    m = InfiniteMaze(seed, k)
    t = m.torches_in(-span, -span, 2 * span, 2 * span)
    check("torches exist", len(t) > 0, f"{len(t)} in a {2 * span}x{2 * span} box")

    p = np.array([[x, z] for x, _, z, *_ in t])
    if len(p) > 1:
        d2 = ((p[:, None, :] - p[None, :, :]) ** 2).sum(-1)
        np.fill_diagonal(d2, np.inf)
        closest = float(np.sqrt(d2.min()))
    else:
        closest = float("inf")
    check("no two torches closer than the spacing", closest >= m.spacing - 1e-6,
          f"closest pair {closest:.2f} vs spacing {m.spacing:.2f} grid units")

    # the same torches, reached through a different set of query boxes
    m2 = InfiniteMaze(seed, k, cache=8)
    quarters = []
    for dc in (0, 1):
        for dr in (0, 1):
            quarters += m2.torches_in(-span + dc * span, -span + dr * span, span, span)
    check("torch set does not depend on the query box",
          sorted(x[3:] for x in t) == sorted(x[3:] for x in quarters),
          f"{len(t)} vs {len(quarters)}")

    on_wall = all(m.has_wall(c, r, d) for *_, c, r, d in t)
    check("every torch sits on a solid wall face", on_wall)


def t_occupancy(seed, k, span):
    m = InfiniteMaze(seed, k)
    occ = m.occupancy(-span, -span, 2 * span, 2 * span)
    check("occupancy skirt is solid on all four sides",
          occ[0, :].all() and occ[-1, :].all() and occ[:, 0].all() and occ[:, -1].all())

    cells_open = (~occ[1::2, 1::2]).sum()
    check("every cell of the box is open floor", cells_open == (2 * span) ** 2,
          f"{cells_open} of {(2 * span) ** 2}")

    # a doorway in the array must correspond to a missing wall, and vice versa
    bad = 0
    for r in range(-span, -span + 2 * span):
        for c in range(-span, -span + 2 * span):
            jr, jc = 2 * (r + span) + 1, 2 * (c + span) + 1
            for d in DIRS:
                nr_, nc_ = jr + DR[d], jc + DC[d]
                if not (0 < nr_ < occ.shape[0] - 1 and 0 < nc_ < occ.shape[1] - 1):
                    continue
                if bool(occ[nr_, nc_]) == (not m.has_wall(c, r, d)):
                    bad += 1
    check("occupancy agrees with the wall bits", bad == 0, f"{bad} mismatched faces")

    # windows that overlap must agree where they overlap
    a = m.occupancy(0, 0, 16, 16)
    b = m.occupancy(8, 8, 16, 16)
    ov_a = a[2 * 8:2 * 16, 2 * 8:2 * 16]
    ov_b = b[0:2 * 8, 0:2 * 8]
    # compare interior only: each window's own skirt is solid by construction
    check("overlapping windows agree in their overlap",
          np.array_equal(ov_a[1:, 1:], ov_b[1:, 1:]))


def t_cost(seed, k):
    """Endless is only real if cost per cell does not grow with distance walked."""
    import time
    m = InfiniteMaze(seed, k, cache=256)
    times = []
    for leg, base in enumerate([0, 500, 20000, 1000000]):
        t0 = time.perf_counter()
        m.occupancy(base, base, 24, 24)
        m.torches_in(base, base, 24, 24)
        times.append(time.perf_counter() - t0)
    ratio = max(times) / min(times)
    check("cost of a window is flat with distance from the origin", ratio < 3.0,
          " ".join(f"{t * 1e3:.0f}ms" for t in times))


def t_pixel_convention(seed, chunk, span):
    """the unprojection must land on the rays the raycaster actually drew

    render.py samples pixel i at image coordinate i + 0.5; the helper that turns the
    model's depth back into splat means samples it at i. Both are fine alone. Sharing
    one K between them aims every ray half a pixel off, which displaces every splat in
    every tile by z*sqrt(2)*0.5/fx -- 8.3 mm here, and a coherent lift of the whole
    tile once the rig's yaws average out. Nothing downstream can see it: the tile is
    self-consistent, the alignment RMSE is unchanged, and the floor lands where it
    should. The only thing that catches it is unprojecting depth we drew ourselves and
    demanding the points come back on the rays that drew it.
    """
    try:
        import math, torch
        _here = os.path.dirname(os.path.abspath(__file__))
        sys.path.insert(0, _here)
        sys.path.insert(0, os.path.abspath(os.path.join(_here, "..", "..", "..")))
        import render as R, tiles as T
        from infinite_maze import EYE_H
        from hyworld2.worldrecon.hyworldmirror.models.utils.geometry import (
            depth_to_world_coords_points)
    except Exception as e:                       # torch/model utils absent: not a failure
        print(f"  SKIP  {type(e).__name__}: {e}")
        return

    spec = T.TileSpec()
    W, H = spec.wh()
    fx = (W / 2) / math.tan(spec.fov_x / 2)
    maze = InfiniteMaze(seed=seed)
    win = R.build_window(maze, -4, -4, 10, 10, device="cpu")
    yaw, pitch, pos = 0.7, 0.2, (2.5, EYE_H, 2.5)
    d = R.render_depth_tensor(win, pos, yaw, pitch, width=W, height=H, fov_x=spec.fov_x)

    dirs, _ = R._ray_dirs(W, H, spec.fov_x, yaw, pitch, "cpu")
    xs = (torch.arange(W).float() - W / 2 + 0.5) / fx
    ys = (torch.arange(H).float() - H / 2 + 0.5) / fx
    yy, xx = torch.meshgrid(ys, xs, indexing="ij")
    cam = torch.stack([xx, yy, torch.ones_like(xx)], -1).reshape(-1, 3)
    t = (d.reshape(-1) / CELL_M) * cam.norm(dim=1)
    o = torch.tensor(win.to_local(pos)).float()
    hit = (o.unsqueeze(0) + dirs * t.unsqueeze(1)) * CELL_M

    e = torch.eye(4).unsqueeze(0)
    e[0, :3, :3] = torch.from_numpy(R.camera_basis(yaw, pitch))
    e[0, :3, 3] = torch.tensor([p * CELL_M for p in win.to_local(pos)])
    K = torch.tensor([[fx, 0, W / 2], [0, fx, H / 2], [0, 0, 1]]).float().unsqueeze(0)
    m = d.reshape(-1) > 0.05
    p, _, _ = depth_to_world_coords_points(d.unsqueeze(0), e, T.pixel_centre_K(K))
    err = float((p.reshape(-1, 3)[m] - hit[m]).norm(dim=1).max())
    check("unprojected depth lands on the ray that drew it", err < 1e-5,
          f"max {err * 1000:.4f} mm over {int(m.sum()):,} pixels")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1000)
    ap.add_argument("--chunk", type=int, default=CHUNK)
    ap.add_argument("--span", type=int, default=24)
    a = ap.parse_args()

    print(f"infinite maze selftest  seed={a.seed} chunk={a.chunk} span=+-{a.span}\n")
    for fn in (t_determinism, t_gate_agreement, t_chunk_internally_connected):
        print(fn.__doc__.splitlines()[0] if fn.__doc__ else fn.__name__)
        fn(a.seed, a.chunk)
    for fn in (t_wall_symmetry, t_plane_connectivity, t_torches, t_occupancy,
               t_pixel_convention):
        print(fn.__doc__.splitlines()[0] if fn.__doc__ else fn.__name__)
        fn(a.seed, a.chunk, a.span)
    print("cost")
    t_cost(a.seed, a.chunk)

    print()
    if FAILS:
        print(f"FAILED: {len(FAILS)} -> {', '.join(FAILS)}")
        sys.exit(1)
    print("ALL PASS")


if __name__ == "__main__":
    main()
